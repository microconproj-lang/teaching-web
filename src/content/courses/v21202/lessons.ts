import type {
  BlueprintSlideDef,
  InteractiveLessonDef,
  LessonResourceDef,
} from "@/core/config/curriculum-types";

function makeMicrobitSlides(unitFolder: string, count: number): BlueprintSlideDef[] {
  return Array.from({ length: count }, (_, idx) => {
    const num = String(idx + 1).padStart(2, "0");
    return {
      src: `/courses/v21202/slides/${unitFolder}/slide-${num}.webp`,
      title: `สไลด์ที่ ${idx + 1}`,
    };
  });
}

function makeMicrobitResources(
  unitFolder: string,
  unitNo: number,
  includeWorkbook = true
): LessonResourceDef[] {
  const list: LessonResourceDef[] = [
    {
      label: `คู่มือครู Unit ${unitNo} (Educator Guide .docx)`,
      kind: "knowledge",
      href: `/courses/v21202/sheets/${unitFolder}-educator-guide.docx`,
    },
  ];
  if (includeWorkbook) {
    list.push({
      label: `ใบงานนักเรียน Unit ${unitNo} (Student Workbook .docx)`,
      kind: "worksheet",
      href: `/courses/v21202/sheets/${unitFolder}-student-workbook.docx`,
    });
  }
  return list;
}

